def _get_channel_library(channel_id: Optional[int]) -> dict:
    """获取频道词库，无配置时返回默认词库。"""
    if channel_id is None or channel_id not in _CHANNEL_STYLE_LIBRARY:
        return {
            "intro_candidates": _DEFAULT_INTRO_CANDIDATES,
            "transition_candidates": _DEFAULT_TRANSITION_CANDIDATES,
            "synonym_replacements": _DEFAULT_SYNONYM_REPLACEMENTS,
            "style_traits": _DEFAULT_STYLE_TRAITS,
        }
    return _CHANNEL_STYLE_LIBRARY[channel_id]


def get_style_hint(
    channel_id: Optional[int],
    seq: int,
    total_segments: int = 1,
    channel_type: Optional[str] = None,
) -> str:
    """构建风格提示字符串，追加到 prompt 末尾。

    按 seq 号轮换选取开场白与过渡词，保证单期节目内不重复。
    seq=1 时使用开场白（intro），seq>=2 时使用过渡词（transition）。
    同义词替换映射整体注入，LLM 自行择机使用。

    Args:
        channel_id: 频道 ID，None 用默认词库
        seq: 当前段在整期节目中的序号（1-based）
        total_segments: 整期节目总段数，用于估算循环周期
        channel_type: 频道类型（news/course/audiobook）。
            channel_type=course 时：若该频道已按 ID 定制专属词库则优先使用之，
            否则使用课程讲师词库（不依赖具体 channel_id）；
            其余频道按 channel_id 匹配频道特定词库，再回退默认词库

    Returns:
        风格提示文本，含开场白/过渡词/同义词/风格定位四部分
    """
    # 课程频道：若该频道已按 ID 定制专属词库则优先使用之（与 rewrite 模板
    # 覆盖约定对称），否则回退课程讲师词库（不依赖具体 channel_id）；
    # 其余频道按 channel_id 或默认。
    if channel_type == "course" and (
        channel_id is None or channel_id not in _CHANNEL_STYLE_LIBRARY
    ):
        lib = _COURSE_LIBRARY
    else:
        lib = _get_channel_library(channel_id)

    # seq=1 用开场白，seq>=2 用过渡词
    # 轮换策略：seq % len 选取，保证 total_segments > len 时不立即重复
    if seq <= 1:
        candidates = lib["intro_candidates"]
        idx = (seq - 1) % len(candidates)
        picked = candidates[idx]
